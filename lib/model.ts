// Launch Radar model "radar-2": one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols by the value a token would carry if the
// protocol's record stayed as it is. It never predicts whether or when a token
// is issued; the implied value is the model's own claim, not a price.
//
// How one protocol is scored (no protocol name is ever special-cased):
//
//   multiple   the market's own price for a dollar of TVL in this category:
//              the median market-cap-to-TVL ratio of the protocols in the same
//              category whose token already trades, taken from this snapshot.
//              A category with fewer than 3 such protocols falls back to the
//              global median over all live-token protocols. Clamped to
//              [0.05, 1.50] so one outlier cannot set the price.
//   base       tvl_usd x multiple
//   growth     change_7d clamped to [-50, 100] per cent
//   growthMult 1 + (growth / 100) x 0.6
//   maturity   0.70 + 0.30 x min(age_days, 1460) / 1460; a protocol whose
//              listed_at is unknown scores 0.85. Older with no token scores
//              higher: it has survived longer on its own record.
//   implied    max(1, round(base x growthMult x maturity))
//
// The board covers every slug on the snapshot's watchlist (the floor, never a
// ceiling) and adds every rankable pre-token protocol below the floor: a
// protocol is rankable when it records no token, is not a versioned pool, and
// is not a wrapped, staked, bridged or exchange product of a token that
// already trades. Live-token protocols are never ranked; they are shown apart
// in the dashboard's Live view at the market's own value.

/** One protocol of the sealed snapshot: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

